	void Translator::Initialize()
	{
		if (m_Initialized)
			return;

#ifdef _WIN32
		// 设置控制台为 UTF-8 模式
		SetConsoleOutputCP(65001);
		SetConsoleCP(65001);
#endif

		InitializeChineseTranslations();
		m_Initialized = true;
	}

	std::string Translator::Get(const std::string& key)
	{
		if (!m_Initialized)
			Initialize();

		auto it = m_Translations.find(key);
		if (it != m_Translations.end())
			return it->second;

		return key;
	}
